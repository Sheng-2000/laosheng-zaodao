def apply(D, news_target=5, other_target=2, verbose=True):
    n1 = n2 = 0
    bad_news, bad_other = [], []
    for k in NEWS_KEYS:
        if k in D:
            D[k] = boost_one(D[k], news_target)
            n = len(re.findall(r'<span style="color:', str(D[k])))
            n1 += 1
            if n < news_target:
                bad_news.append((k, n))
    for k in OTHER_KEYS:
        if k in D:
            D[k] = boost_one(D[k], other_target)
            n = len(re.findall(r'<span style="color:', str(D[k])))
            n2 += 1
            if n < other_target:
                bad_other.append((k, n))
    if verbose:
        print("=== 高亮密度增强 ===")
        print(f"  新闻/AI卡: {n1 - len(bad_news)}/{n1} 达标(≥{news_target})")
        if bad_news:
            print("    未达标:", bad_news)
        print(f"  其余文本卡: {n2 - len(bad_other)}/{n2} 达标(≥{other_target})")
        if bad_other:
            print("    未达标:", bad_other)
    return bad_news, bad_other
