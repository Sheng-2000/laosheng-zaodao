def _mkpat(words):
    return "|".join(sorted((re.escape(w) for w in words), key=len, reverse=True))


def boost_one(text, target):
    """把 text 的高亮数补到 target（已有的高亮会被计数并保护）"""
    if not isinstance(text, str) or not text:
        return text
    store = []

    def _pf(m):
        store.append(m.group(0))
        return "\x00" + str(len(store) - 1) + "\x00"

    s = re.sub(r'<span style="color:[^"]*">[\s\S]*?</span>', _pf, text)

    def _sub(pat, color):
        nonlocal s

        def f(m):
            store.append('<span style="color:' + color + '">' + m.group(0) + "</span>")
            return "\x00" + str(len(store) - 1) + "\x00"

        s = re.sub(pat, f, s)

    rules = [
        (r"\+" + _num + r"%", _UP),
        (r"-\s*" + _num + r"%", _DOWN),
        (r"涨(?:了|至|超|近|约)?" + _num + r"%", _UP),
        (r"跌(?:了|至|超|近|约)?" + _num + r"%", _DOWN),
        (_mkpat(_UPW), _UP),
        (_mkpat(_DNW), _DOWN),
        (_num + r"(?:万亿|亿元|亿美元|万美元|亿|万元|美元|港元|点|BP|bp|倍|家|只|元)", _CYAN),
        (_num + r"%", _CYAN),
    ]
    for pat, color in rules:
        if len(store) >= target:
            break
        _sub(pat, color)
    for words, color in ((_YEW, _YELLOW), (_ENT, _YELLOW), (_ORG, _YELLOW), (_TEC, _CYAN), (_ORW, _ORANGE)):
        if len(store) >= target:
            break
        _sub(_mkpat(words), color)

    return re.sub(r"\x00(\d+)\x00", lambda m: store[int(m.group(1))], s)


